/**
 * Golden baseline for the deterministic eval suite.
 *
 * eval/det/baseline.json is committed and reviewed. It holds the deterministic
 * contract we refuse to change silently:
 *   - the morning `dataSha256` for the fixed fixture and fixed --now;
 *   - the SHA-256 of the deterministic morning markdown;
 *   - the exit-code map (0 success / 1 user error / 3 TOS);
 *   - the required MCP tool/resource surface and the legacy protocol version.
 *
 * Re-record only with `node scripts/eval-det.mjs --update-baseline` after
 * reviewing the diff. Making a real regression green by re-recording the
 * baseline is exactly the failure this file exists to prevent.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { BASELINE_PATH, CLI_VERSION, NODE_VERSION, cleanupWorkdir, createWorkdir, parseJson, runCli, sha256Hex } from './harness.mjs'
import { GOLDEN_NOW, seedMorningLedger } from '../fixtures/morning-ledger.mjs'

const REQUIRED_TOOLS = [
  'advisers_today',
  'advisers_commit_ls',
  'advisers_who',
  'advisers_evidence',
  'advisers_remind',
  'advisers_capture_candidate',
  'advisers_pack_verify',
]
const REQUIRED_RESOURCES = ['advisers://today', 'advisers://commitments', 'advisers://who', 'advisers://evidence']

/** Read and validate the committed baseline; throws with an actionable message. */
export function readBaseline() {
  let baseline
  try {
    baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'))
  } catch (error) {
    throw new Error('eval/det/baseline.json is missing or unreadable: ' + String(error?.message ?? error))
  }
  if (baseline.schemaVersion !== 1) throw new Error('eval/det/baseline.json: unsupported schemaVersion ' + baseline.schemaVersion)
  if (typeof baseline.golden?.morning?.dataSha256 !== 'string') throw new Error('eval/det/baseline.json: golden.morning.dataSha256 is missing')
  return baseline
}

/**
 * Re-record the golden hash/markdown values from the current tree.
 * Contract expectations (tools/resources/exit codes) are kept as-is.
 */
export async function recordBaseline() {
  let current = null
  try { current = readBaseline() } catch { current = null }
  const workdir = createWorkdir('baseline')
  try {
    await seedMorningLedger(workdir.home)
    const jsonRun = runCli(workdir, ['morning', '--now', GOLDEN_NOW, '--json'], { index: 'baseline-json' })
    const parsed = parseJson(jsonRun.stdout)
    if (jsonRun.status !== 0 || !parsed.ok) {
      throw new Error('baseline recording failed: morning --json exit ' + jsonRun.status + '; ' + (parsed.error ?? jsonRun.stderr.slice(0, 300)))
    }
    const markdownRun = runCli(workdir, ['morning', '--now', GOLDEN_NOW], { index: 'baseline-md' })
    if (markdownRun.status !== 0) throw new Error('baseline recording failed: morning exit ' + markdownRun.status)
    const baseline = {
      schemaVersion: 1,
      suiteVersion: 1,
      fixture: current?.fixture ?? 'morning-ledger-v1',
      recordedAt: new Date().toISOString(),
      recordedFrom: { cliVersion: CLI_VERSION, node: NODE_VERSION },
      golden: {
        morning: {
          now: GOLDEN_NOW,
          localDay: parsed.value.localDay,
          dataSha256: parsed.value.dataSha256,
          digestMarkdownSha256: sha256Hex(markdownRun.stdout),
        },
      },
      contract: current?.contract ?? {
        exitCodes: { success: 0, userError: 1, tosRequired: 3 },
        mcp: {
          initializeEchoVersions: ['2024-11-05'],
          requiredTools: REQUIRED_TOOLS,
          requiredResources: REQUIRED_RESOURCES,
        },
      },
      notes: [
        'Generated by node scripts/eval-det.mjs --update-baseline; review the diff before committing.',
        'A change here means the deterministic contract (morning hash / markdown / MCP surface) changed.',
      ],
    }
    writeFileSync(BASELINE_PATH, JSON.stringify(baseline, null, 2) + '\n')
    return { baseline }
  } finally {
    cleanupWorkdir(workdir)
  }
}

export { REQUIRED_TOOLS, REQUIRED_RESOURCES }
